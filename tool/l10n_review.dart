// Generates docs/l10n/FRENCH-REVIEW.md from lib/l10n/app_en.arb + app_fr.arb.
//
//   fvm dart run tool/l10n_review.dart
//
// The doc is for the native French reviewer; regenerate it after any ARB edit.
import 'dart:convert';
import 'dart:io';

/// Non-breaking space, shown as a visible mark so the reviewer keeps it.
const _nbsp = ' ';
const _nbspMark = '⍽'; // ⍽

/// Strings the implementers were least sure about: key -> why.
const _uncertain = <String, String>{
  'navChats': '"Messages" (vs "Discussions": too long for the tab at 2.0x)',
  'navRequests': '"Demandes" (vs "Invitations")',
  'phoneVerify': '"Valider" (vs "Vérifier")',
  'settingsTitle': '"Réglages" (vs "Paramètres"; matches iOS "Réglages")',
  'mealHostFallbackName': '"Hôte" (vs "Organisateur/Organisatrice")',
  'inboxGuestFallback': '"Convive" as the neutral word for a guest',
  'mealActionNotSelected': '"Pas cette fois" (gender-neutral "not selected")',
  'mealActionStatusApproved': '"C’est un match !" (anglicism "match")',
  'mealDetailOpenInMaps': '"Ouvrir dans Maps" (Apple Maps is "Plans")',
  'ratingBadgeNew': '"Nouveau" (masculine default for a new profile)',
  'settingsContactSupport': '"Contacter l’assistance"',
  'mealActionStatusYourMeal':
      '"Tes demandes : onglet Demandes." (terse: width)',
  'mealActionStatusWomenOnly': '"Réservé aux femmes." (terse: width)',
  'mealWomenOnly': '"Entre femmes" for "Women only"',
  'safetyTipsBanner': 'free translation of "Meeting up?"',
  'createMealNoteLabel': '"Note" (facultative) for the meal note field',
  'inboxActionChat': '"Discuter" vs "Ouvrir la discussion"',
  'settingsSectionLegal': '"Informations légales"',
  'setupSubtitle': '"genre" for gender',
  'errorStateTitle': '"Chargement impossible" (generic, many screens)',
  'discoverEmptyMessage': 'avoids the gendered "Sois le premier / la première"',
};

String _cell(String s) =>
    s.replaceAll('|', r'\|').replaceAll('\n', ' ').replaceAll(_nbsp, _nbspMark);

String _where(String key) {
  final word = RegExp('\\b$key\\b');
  final files = <String>[];
  for (final f in Directory('lib').listSync(recursive: true)) {
    if (f is! File || !f.path.endsWith('.dart')) continue;
    if (f.path.startsWith('lib/l10n/')) continue;
    if (word.hasMatch(f.readAsStringSync())) files.add(f.path);
  }
  files.sort(); // listSync order is not stable across machines
  return files.isEmpty ? 'n/a' : files.join(', ');
}

void main() {
  Map<String, dynamic> load(String name) =>
      jsonDecode(File('lib/l10n/$name').readAsStringSync())
          as Map<String, dynamic>;
  final en = load('app_en.arb');
  final fr = load('app_fr.arb');
  final keys = en.keys.where((k) => !k.startsWith('@')).toList();
  String describe(String k) =>
      ((en['@$k'] as Map<String, dynamic>?)?['description'] as String?) ?? '';

  final b = StringBuffer()
    ..writeln('# French review (needs native review)')
    ..writeln()
    ..writeln('> **Needs native review.** The French was drafted by the')
    ..writeln('> developer, not by a native speaker. Do not ship to the')
    ..writeln('> stores before it has been read through.')
    ..writeln()
    ..writeln('Generated by `fvm dart run tool/l10n_review.dart`; do not edit')
    ..writeln('this file by hand to change copy, change `lib/l10n/app_fr.arb`.')
    ..writeln()
    ..writeln('## How to review')
    ..writeln()
    ..writeln('1. Read the table below; edit the **French** column (or send')
    ..writeln('   a list of `key -> new French`).')
    ..writeln('2. Apply each change to `lib/l10n/app_fr.arb` (same key).')
    ..writeln('3. Run `fvm flutter gen-l10n`, then `fvm flutter test`: the')
    ..writeln('   `*_fr_test.dart` files assert the exact French text, so a')
    ..writeln('   changed string needs the matching test expectation updated.')
    ..writeln('4. Re-run `fvm dart run tool/l10n_review.dart` to refresh this')
    ..writeln('   file.')
    ..writeln()
    ..writeln('Conventions to keep: informal "tu"; short and warm like the')
    ..writeln('English; brand "Convyve"; typographic apostrophe ’ (never the')
    ..writeln(
      'ASCII one); keep `{placeholders}` as they are. $_nbspMark marks a',
    )
    ..writeln('non-breaking space (U+00A0, before `: ! ? ;`, inside « », and')
    ..writeln('between a number and min/h/j/s/km): keep it as a real NBSP in')
    ..writeln('the ARB. Strings are short because the meal action bar and')
    ..writeln('buttons are fixed width: check any longer rewording at 320 px.')
    ..writeln()
    ..writeln('## Strings the implementers were unsure about')
    ..writeln();
  for (final e in _uncertain.entries) {
    if (!en.containsKey(e.key)) {
      stderr.writeln('warning: unknown key in _uncertain: ${e.key}');
      continue;
    }
    b.writeln(
      '- `${e.key}`: ${e.value} -> now '
      '"${_cell(fr[e.key] as String)}"',
    );
  }

  final longest = [...keys]
    ..sort(
      (a, c) => (fr[c] as String).length.compareTo((fr[a] as String).length),
    );
  b
    ..writeln()
    ..writeln('## 10 longest French strings')
    ..writeln()
    ..writeln('| key | length | French | used in |')
    ..writeln('| --- | ---: | --- | --- |');
  for (final k in longest.take(10)) {
    final v = fr[k] as String;
    b.writeln('| `$k` | ${v.length} | ${_cell(v)} | ${_where(k)} |');
  }

  b
    ..writeln()
    ..writeln('## All strings (${keys.length})')
    ..writeln()
    ..writeln('| key | English | French | description |')
    ..writeln('| --- | --- | --- | --- |');
  for (final k in keys) {
    b.writeln(
      '| `$k` | ${_cell(en[k] as String)} | '
      '${_cell(fr[k] as String)} | ${_cell(describe(k))} |',
    );
  }

  Directory('docs/l10n').createSync(recursive: true);
  File('docs/l10n/FRENCH-REVIEW.md').writeAsStringSync(b.toString());
  stdout.writeln('wrote docs/l10n/FRENCH-REVIEW.md (${keys.length} keys)');
}
